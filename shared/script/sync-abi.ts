// Copies the DeadPool ABI and bytecode from the Foundry build output into
// shared/src/abi.ts so the judge, scripts and web app use the same interface.
// Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../contracts/out/DeadPool.sol/DeadPool.json");
const target = resolve(here, "../src/abi.ts");

const json = JSON.parse(readFileSync(artifact, "utf8"));
const out = `// Generated by shared/scripts/sync-abi.ts from contracts/out. Do not edit by hand.
export const deadPoolAbi = ${JSON.stringify(json.abi, null, 2)} as const;

export const deadPoolBytecode = "${json.bytecode.object}" as const;
`;
writeFileSync(target, out);
console.log(`Wrote ${target} (${json.abi.length} ABI entries)`);
